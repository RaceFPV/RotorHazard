//! Embed the plugin bridge so plugin support ships inside the single binary.
//!
//! The bridge is a Python program (the RHAPI facade + shim modules). Python
//! cannot be linked into a Rust binary, so instead the bytes are embedded here
//! and written to `<data_dir>/bridge/` on first run — and rewritten whenever
//! this binary's copy differs. Users never fetch or version the bridge; it
//! travels with the server, so upgrading is still "replace one binary".

use std::collections::hash_map::DefaultHasher;
use std::fs;
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let bridge_root = manifest_dir.join("../plugin-bridge");

    // The bridge sources are crate inputs; cargo must rebuild when they change
    // or the embedded copy would drift from the files on disk.
    println!("cargo:rerun-if-changed={}", bridge_root.display());

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect(&bridge_root, &bridge_root, &mut files);
    files.sort();

    let mut hasher = DefaultHasher::new();
    for (rel, path) in &files {
        rel.hash(&mut hasher);
        fs::read_to_string(path).unwrap_or_default().hash(&mut hasher);
    }
    let revision = format!("{:016x}", hasher.finish());

    let mut out = String::new();
    out.push_str("// Generated by build.rs: the embedded plugin bridge.\n");
    out.push_str(&format!(
        "pub const BRIDGE_REVISION: &str = \"{}\";\n",
        revision
    ));
    out.push_str("pub const BRIDGE_FILES: &[(&str, &str)] = &[\n");
    for (rel, path) in &files {
        out.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            rel,
            path.to_string_lossy()
        ));
    }
    out.push_str("];\n");

    let out_path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("bridge_assets.rs");
    fs::write(&out_path, out).expect("write bridge_assets.rs");
}

/// Only what runs: the entry point and the rh_compat package. Test harnesses and
/// fixtures stay in the repo and are not shipped to users.
fn wanted(rel: &str) -> bool {
    rel == "rhapi_bridge.py" || rel.starts_with("rh_compat/")
}

fn collect(root: &Path, dir: &Path, into: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            // __pycache__ is produced by running the bridge, not source.
            if path.file_name().map(|n| n == "__pycache__").unwrap_or(false) {
                continue;
            }
            collect(root, &path, into);
            continue;
        }
        if path.extension().map(|e| e != "py").unwrap_or(true) {
            continue;
        }
        let rel = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        if wanted(&rel) {
            into.push((rel, path));
        }
    }
}
