"""Inventory the WHOLE RHAPI surface and what the bridge/server provide.

Writes rust/plugin-bridge/RHAPI-COVERAGE.md. Unlike gen_compat_matrix.py, which
measures one plugin's usage, this counts every public member of the real RHAPI
(RHAPI.py) across all namespaces.
"""
import ast
import re

REPO = "/home/racefpv/git/RotorHazard"
RHAPI = REPO + "/src/server/RHAPI.py"
BRIDGE = REPO + "/rust/plugin-bridge/rhapi_bridge.py"
RPC = REPO + "/rust/server/src/pluginrpc.rs"
OUT = REPO + "/rust/plugin-bridge/RHAPI-COVERAGE.md"

# RHAPI class -> the attribute it is exposed as on the rhapi object.
CLASS_TO_ATTR = {
    "UserInterfaceAPI": "ui",
    "FieldsAPI": "fields",
    "DatabaseAPI": "db",
    "IOAPI": "io",
    "HeatGenerateAPI": "heatgen",
    "ClassRankAPI": "classrank",
    "PointsAPI": "points",
    "LEDAPI": "led",
    "VRxControlAPI": "vrxcontrol",
    "RaceAPI": "race",
    "LanguageAPI": "language",
    "HardwareInterfaceAPI": "interface",
    "ServerConfigAPI": "config",
    "SensorsAPI": "sensors",
    "EventResultsAPI": "eventresults",
    "EventsAPI": "events",
    "ServerAPI": "server",
    "FilterAPI": "filters",
    "UtilsAPI": "utils",
}

# Bridge class -> namespace it serves.
BRIDGE_CLASS_TO_ATTR = {
    "Db": "db",
    "Race": "race",
    "UI": "ui",
    "Fields": "fields",
    "Config": "config",
    "Utils": "utils",
    "Events": "events",
    "Filters": "filters",
    "Sensors": "sensors",
    "Server": "server",
    "Language": "language",
    "Led": "led",
    "VRxControl": "vrxcontrol",
    "HeatGen": "heatgen",
    "Io": "io",
}

tree = ast.parse(open(RHAPI, encoding="utf-8").read())
surface = {}
for node in tree.body:
    if not isinstance(node, ast.ClassDef) or node.name not in CLASS_TO_ATTR:
        continue
    attr = CLASS_TO_ATTR[node.name]
    members = []
    for item in node.body:
        if isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
            members.append(item.name)
    surface[attr] = sorted(set(members))

bridge = ast.parse(open(BRIDGE, encoding="utf-8").read())
bridge_members = {}
for node in bridge.body:
    if isinstance(node, ast.ClassDef) and node.name in BRIDGE_CLASS_TO_ATTR:
        names = set()
        for item in node.body:
            if isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
                names.add(item.name)
        bridge_members[BRIDGE_CLASS_TO_ATTR[node.name]] = names

# classrank and points share one bridge class (Registry).
registry_members = set()
for node in bridge.body:
    if isinstance(node, ast.ClassDef) and node.name == "Registry":
        registry_members = {i.name for i in node.body
                            if isinstance(i, ast.FunctionDef) and not i.name.startswith("_")}
bridge_members["classrank"] = registry_members
bridge_members["points"] = registry_members

rpc = open(RPC, encoding="utf-8").read()
server_arms = {"%s.%s" % (o, m) for o, m in re.findall(r'\(\s*"([a-z_]+)"\s*,\s*"([a-z_]+)"\s*\)', rpc)}

rows = []
for attr in sorted(surface):
    missing = []
    for member in surface[attr]:
        key = "%s.%s" % (attr, member)
        provided = key in server_arms or member in bridge_members.get(attr, set())
        rows.append((attr, member, provided))
        if not provided:
            missing.append(member)

total = len(rows)
provided = sum(1 for _, _, ok in rows if ok)

lines = [
    "# RHAPI coverage (whole API, not one plugin)",
    "",
    "Generated by rust/tools/gen_rhapi_coverage.py from src/server/RHAPI.py,",
    "rhapi_bridge.py and pluginrpc.rs. `yes` means the bridge provides it as a",
    "method/property or the server answers the matching RPC arm.",
    "",
    "| namespace | provided | total |",
    "|---|---|---|",
]
for attr in sorted(surface):
    n = len(surface[attr])
    ok = sum(1 for a, _, good in rows if a == attr and good)
    lines.append("| rhapi.%s | %d | %d |" % (attr, ok, n))
lines += [
    "| **total** | **%d** | **%d** |" % (provided, total),
    "",
    "## Missing members",
    "",
]
for attr in sorted(surface):
    miss = [m for a, m, good in rows if a == attr and not good]
    if miss:
        lines.append("- **%s** (%d): %s" % (attr, len(miss), ", ".join("`%s`" % m for m in miss)))

lines += [
    "",
    "## Known approximations",
    "",
    "These are present (so they import and run) but do not reproduce the Python",
    "behaviour; a plugin that depends on the exact semantics will notice:",
    "",
    "- `db.open_readonly` raises: it returns a live SQLAlchemy session, and the",
    "  Rust server owns its SQLite connection.",
    "- `io.run_export` / `io.run_import` raise: export/import run server-side.",
    "- `heatgen.generate` raises: heat generation is driven from the UI.",
    "- `eventresults.results`, `db.event_results` return null: the Rust server has",
    "  no event-results cache yet.",
    "- `interface.*`: the Rust server owns node providers, so registrations are",
    "  accepted and the read-only views report seats/mock signals generically.",
    "- `server.enable_heartbeat_event`, `set_min_mocks`, `set_restart_required`,",
    "  `db.race_results_rebuild`, `ui.blueprint_add` return true as accepted",
    "  no-ops.",
]


open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("wrote", OUT)
print("coverage: %d/%d" % (provided, total))
for attr in sorted(surface):
    n = len(surface[attr])
    ok = sum(1 for a, _, good in rows if a == attr and good)
    print("  %-12s %3d/%-3d" % (attr, ok, n))
